export type MessageCatalogue = {
  [Key in keyof MessageParameters]: MessageParameters[Key] extends undefined
    ? () => string
    : (params: MessageParameters[Key]) => string;
};

export type Translator = <Key extends keyof MessageParameters>(
  ...args: MessageParameters[Key] extends undefined
    ? [key: Key]
    : [key: Key, params: MessageParameters[Key]]
) => string;

const CATALOGUES: Record<UiLocale, MessageCatalogue> = { en, fr };

export function createTranslator(locale: UiLocale): Translator {
  return ((key: keyof MessageParameters, params?: never) =>
    (CATALOGUES[locale][key] as (value?: never) => string)(params)) as Translator;
}
